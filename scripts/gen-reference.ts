// Writes docs/reference/cli.md and errors.md from the built CLI's `help --json`, so the pages
// document exactly what an agent receives. Run it with `pnpm docs:reference`.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

// The shape of `jm help --json`, which apps/cli/src/help.ts owns. Scripts cannot import across packages.
interface OptionDoc {
  flag: string
  type: string
  description: string
  required: boolean
  default: string | number | boolean | null
  repeatable: boolean
  clearable: boolean
  choices: string[] | null
  conflicts: string[]
}

interface CommandDoc {
  id: string
  usage: string
  description: string
  args: {
    name: string
    type: string
    description: string
    required: boolean
    variadic: boolean
    choices: string[] | null
  }[]
  options: OptionDoc[]
  examples: { command: string; description: string }[]
  output: { summary: string; example: unknown }
  exits: { code: string; exit: number; when: string }[]
  writes: string[]
  calls: string[]
}

interface HelpDoc {
  globalOptions: OptionDoc[]
  exitCodes: { exit: number; code: string | null; meaning: string; fix?: string }[]
  commands: CommandDoc[]
}

const root = new URL('../', import.meta.url)
const cli = fileURLToPath(new URL('apps/cli/dist/index.js', root))

function readHelp(): HelpDoc {
  // Piped stdout puts the CLI in JSON mode, so no flag is needed.
  const stdout = execFileSync(process.execPath, [cli, 'help', '--json'], { encoding: 'utf8' })
  return (JSON.parse(stdout) as { data: HelpDoc }).data
}

const cell = (text: string) => text.replaceAll('|', '\\|').replaceAll('\n', ' ')
const code = (text: string) => `\`${text}\``
const table = (header: string[], rows: string[][]) =>
  [
    `| ${header.join(' | ')} |`,
    `|${header.map(() => '---').join('|')}|`,
    ...rows.map((row) => `| ${row.map(cell).join(' | ')} |`),
  ].join('\n')

function optionNotes(o: OptionDoc): string {
  const notes = [o.description]
  if (o.choices) notes.push(`One of ${o.choices.join(', ')}.`)
  if (o.repeatable) notes.push('Repeatable.')
  if (o.clearable) notes.push('`none` clears it.')
  if (o.conflicts.length > 0)
    notes.push(`Conflicts with ${o.conflicts.map((c) => `\`--${c}\``).join(', ')}.`)
  return notes.join(' ')
}

const optionRow = (o: OptionDoc) => [
  code(o.flag),
  o.type,
  o.required ? 'yes' : 'no',
  o.default === null ? '' : code(String(o.default)),
  optionNotes(o),
]

function commandSection(c: CommandDoc): string {
  const parts = [`### jm ${c.id}`, '```\n' + c.usage + '\n```', c.description]
  if (c.args.length > 0) {
    parts.push(
      '#### Arguments',
      table(
        ['Argument', 'Type', 'Required', 'Description'],
        c.args.map((a) => [
          code(a.variadic ? `${a.name}...` : a.name),
          a.type,
          a.required ? 'yes' : 'no',
          a.choices ? `${a.description} One of ${a.choices.join(', ')}.` : a.description,
        ]),
      ),
    )
  }
  if (c.options.length > 0) {
    parts.push(
      '#### Options',
      table(['Flag', 'Type', 'Required', 'Default', 'Description'], c.options.map(optionRow)),
    )
  }
  parts.push(
    '#### Examples',
    c.examples.map((e) => `\`\`\`sh\n# ${e.description}\n${e.command}\n\`\`\``).join('\n\n'),
    '#### Output',
    c.output.summary,
    '```json\n' + JSON.stringify({ data: c.output.example }, null, 2) + '\n```',
  )
  if (c.exits.length > 0) {
    parts.push(
      '#### Exits',
      table(
        ['Exit', 'Code', 'When'],
        c.exits.map((e) => [String(e.exit), code(e.code), e.when]),
      ),
    )
  }
  parts.push(
    '#### Effects',
    `Writes: ${c.writes.length > 0 ? c.writes.join(', ') : 'nothing'}.`,
    c.calls.length > 0
      ? `Calls:\n\n${c.calls.map((call) => `- ${code(call)}`).join('\n')}`
      : 'Calls: none.',
  )
  return parts.join('\n\n')
}

function cliPage(doc: HelpDoc): string {
  const nouns = [...new Set(doc.commands.map((c) => c.id.split(' ')[0] ?? ''))]
  const sections = nouns.map((noun) =>
    [
      `## ${noun}`,
      ...doc.commands.filter((c) => c.id.split(' ')[0] === noun).map(commandSection),
    ].join('\n\n'),
  )
  return [
    '# CLI Reference',
    '<!-- Generated by `pnpm docs:reference` from the command schema. Do not edit by hand. -->',
    '## Global Options',
    table(
      ['Flag', 'Type', 'Description'],
      doc.globalOptions.map((o) => [code(o.flag), o.type, o.description]),
    ),
    '## Envelope',
    'With `--json`, or whenever stdout is piped, stdout carries exactly one JSON value. A success is `{"data": ...}`. A failure is `{"error": {"code": "...", "message": "...", "details": ...}}`, where `details` is omitted when empty. Each command below shows its `data`. On a terminal without `--json`, a command prints a table or text, and a failure prints `jm: <message>` to stderr. `--help` and `--version` always print plain text.',
    '## Exit Codes',
    table(
      ['Exit', 'Code', 'Meaning'],
      doc.exitCodes.map((e) => [String(e.exit), e.code === null ? '' : code(e.code), e.meaning]),
    ),
    'Every error code, with its fix, is in [errors.md](errors.md).',
    ...sections,
  ].join('\n\n')
}

function errorsPage(doc: HelpDoc): string {
  const rows = doc.exitCodes.filter((e) => e.code !== null)
  return [
    '# Errors',
    '<!-- Generated by `pnpm docs:reference` from `ERROR_HELP` in packages/core/src/errors.ts. Do not edit by hand. -->',
    'Clients branch on `code`, never on `message`.',
    table(
      ['Exit', 'Code', 'Meaning', 'Fix'],
      rows.map((e) => [String(e.exit), code(e.code ?? ''), e.meaning, e.fix ?? '']),
    ),
  ].join('\n\n')
}

const doc = readHelp()
writeFileSync(new URL('docs/reference/cli.md', root), cliPage(doc) + '\n')
writeFileSync(new URL('docs/reference/errors.md', root), errorsPage(doc) + '\n')
